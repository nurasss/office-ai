export async function seedModelCatalog(db: Database): Promise<void> {
  for (const model of SEED_MODELS) {
    await db
      .insert(models)
      .values(model)
      .onConflictDoUpdate({
        target: models.id,
        set: {
          provider: model.provider,
          modelKey: model.modelKey,
          displayName: model.displayName,
          tier: model.tier,
          contextWindow: model.contextWindow,
          maxOutputTokens: model.maxOutputTokens,
          inputPricePerMillion: model.inputPricePerMillion,
          outputPricePerMillion: model.outputPricePerMillion,
          cachedInputPricePerMillion: model.cachedInputPricePerMillion,
          supportsTools: model.supportsTools,
          supportsStructuredOutput: model.supportsStructuredOutput,
          supportsStreaming: model.supportsStreaming,
          supportsVision: model.supportsVision,
          qualityScore: model.qualityScore,
          avgLatencyMs: model.avgLatencyMs,
          status: model.status,
          pricingVerified: model.pricingVerified,
          pricingVerifiedAt: model.pricingVerifiedAt,
          pricingSourceUrl: model.pricingSourceUrl,
          updatedAt: new Date(),
        },
      })
  }
}
